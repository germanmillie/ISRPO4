import math

def area(r):
    '''Принимает число r, возвращает площадь круга: r * r *math.pi
    Пример вызова: area(7)
    '''
    return math.pi * r * r

def perimeter(r):
    '''Принимает число r, возвращает периметр круга: 2 * math.pi * r
    Пример вызова: perimetr (15)
    '''
    return 2 * math.pi * r

